def test_cli_writes_codex_and_project_configs(tmp_path, monkeypatch, capsys):
    monkeypatch.setenv("CODEX_HOME", str(tmp_path / "codex"))
    assert main(["integrate", "codex", "--write", "--pcp", "pcp"]) == 0
    assert tomllib.loads((tmp_path / "codex" / "config.toml").read_text())["mcp_servers"][MCP_SERVER_NAME]["command"] == "pcp"
    proj = tmp_path / "proj"
    proj.mkdir()
    assert main(["integrate", "claude", "--write", "--project", str(proj)]) == 0
    assert json.loads((proj / ".mcp.json").read_text()) == config.claude_mcp_json(pcp="pcp")
    assert main(["integrate", "codex", "--write", "--project", str(proj)]) == 0
    assert (proj / ".codex" / "config.toml").exists()
    assert main(["integrate", "agents-md", "--write", "--project", str(proj)]) == 0
    assert "pcp skill show prover" in (proj / "AGENTS.md").read_text()
    assert main(["integrate", "claude", "--write"]) == 2  # user scope is `claude mcp add`, never a file we own


def test_cli_write_preserves_a_symlinked_target_and_its_mode(tmp_path, monkeypatch):
    """A dotfiles-managed ``~/.codex/config.toml`` (symlink) and its 0640 mode must
    survive a `pcp integrate codex --write`."""
    codex_home = tmp_path / "codex"
    codex_home.mkdir()
    dotfiles = tmp_path / "dotfiles"
    dotfiles.mkdir()
    real = dotfiles / "config.toml"
    real.write_text('model = "o"\n', encoding="utf-8")
    real.chmod(0o640)
    link = codex_home / "config.toml"
    link.symlink_to(real)
    monkeypatch.setenv("CODEX_HOME", str(codex_home))

    assert main(["integrate", "codex", "--write", "--pcp", "pcp"]) == 0

    assert link.is_symlink() and link.resolve() == real
    assert tomllib.loads(real.read_text())["mcp_servers"][MCP_SERVER_NAME]["command"] == "pcp"
    assert os.stat(real).st_mode & 0o777 == 0o640


