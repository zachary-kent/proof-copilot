def test_plugin_manifest_matches_marketplace_and_package():
    plugin = json.loads((PLUGIN / ".claude-plugin" / "plugin.json").read_text())
    market = json.loads(MARKETPLACE.read_text())
    (entry,) = [p for p in market["plugins"] if p["name"] == plugin["name"]]
    assert (ROOT / entry["source"]).resolve() == PLUGIN.resolve()
    version = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]
    assert plugin["version"] == version, "bump integrations/claude-code/.claude-plugin/plugin.json with pyproject"


@pytest.mark.parametrize("path", PLUGIN_TEXTS, ids=lambda p: p.parent.name if p.name == "SKILL.md" else p.stem)
def test_plugin_text_names_only_real_things(path):
    text = path.read_text()
    front = re.match(r"---\n(.*?)\n---\n", text, re.S)
    assert front and re.search(r"^description: \S", front.group(1), re.M), "frontmatter needs a description"
    if path.name == "SKILL.md":
        assert re.search(rf"^name: {re.escape(path.parent.name)}$", front.group(1), re.M)
    _assert_names_real(text)


def test_agents_md_block_names_only_real_things():
    block = integ.agents_md_block()
    assert all(f"`{t}`" in block for t in TOOLS)
    _assert_names_real(block)


def test_integrations_doc_names_only_real_things():
    _assert_names_real((ROOT / "docs" / "INTEGRATIONS.md").read_text())


def _assert_names_real(text: str) -> None:
    subs = _subcommands()
    # Commands are quoted: inline `pcp x ...` or a code-block line starting `pcp x`.
    for cmd in re.findall(r"(?:`|^)pcp ([a-z][a-z-]*)", text, re.M):
        assert cmd in subs, f"`pcp {cmd}` is not a subcommand"
    for name in re.findall(r"pcp skill show (\w+)", text):
        assert f"{name}.md" in skill_names()
    for tool in set(re.findall(r"\b(proof_[a-z]+|premise_search|notation_resolve|verify_node)\b", text)):
        assert tool in TOOLS, f"{tool} is not an MCP tool"


