# ----------------------------------------------------------------------------- merges
def test_codex_merge_appends_is_idempotent_and_refuses_to_clobber():
    table = config.codex_toml(pcp="pcp")
    base = '# mine\nmodel = "o"\n\n[mcp_servers.other]\ncommand = "x"\n'
    out, changed = integ.merge_codex_toml(base, table)
    assert changed and out.startswith(base)
    assert set(tomllib.loads(out)["mcp_servers"]) == {"other", MCP_SERVER_NAME}
    assert integ.merge_codex_toml(out, table) == (out, False)
    with pytest.raises(UsageError, match="--force"):
        integ.merge_codex_toml(out, config.codex_toml(pcp="/abs/pcp"))


def test_codex_force_replaces_the_table_and_its_subtables():
    old = '[mcp_servers.pcp]\ncommand = "old"\n\n[mcp_servers.pcp.env]\nA = "1"\n\n[profiles.x]\nmodel = "m"\n'
    out, changed = integ.merge_codex_toml(old, config.codex_toml(pcp="new"), force=True)
    doc = tomllib.loads(out)
    assert changed and doc["mcp_servers"][MCP_SERVER_NAME]["command"] == "new"
    assert "env" not in doc["mcp_servers"][MCP_SERVER_NAME] and doc["profiles"] == {"x": {"model": "m"}}


def test_codex_force_on_a_dotted_key_table_is_a_usageerror_not_a_crash():
    """A dotted key under ``[mcp_servers]`` isn't a header ``_drop_table`` can remove, so
    the appended ``[mcp_servers.pcp]`` header collides with it; tomllib refuses to parse
    the result and that must surface as the usual UsageError, not TOMLDecodeError."""
    old = '[mcp_servers]\npcp.command = "old"\n'
    with pytest.raises(UsageError, match="could not rewrite"):
        integ.merge_codex_toml(old, config.codex_toml(pcp="new"), force=True)


def test_codex_force_on_an_inline_table_is_a_usageerror_not_a_crash():
    old = '[mcp_servers]\npcp = { command = "old" }\n'
    with pytest.raises(UsageError, match="could not rewrite"):
        integ.merge_codex_toml(old, config.codex_toml(pcp="new"), force=True)


def test_drop_table_keeps_a_comment_that_precedes_the_next_header():
    old = (
        '[mcp_servers.pcp]\ncommand = "old"\n\n'
        "# NOTE: kept for a reason\n"
        '[mcp_servers.other]\ncommand = "x"\n'
    )
    out, changed = integ.merge_codex_toml(old, config.codex_toml(pcp="new"), force=True)
    assert changed
    assert "# NOTE: kept for a reason" in out
    assert out.index("# NOTE: kept for a reason") < out.index("[mcp_servers.other]")
    assert tomllib.loads(out)["mcp_servers"]["other"]["command"] == "x"


def test_header_regex_does_not_treat_a_nested_array_continuation_line_as_a_header():
    """``args = [\\n  [1, 2],\\n]`` inside the dropped table must not be mistaken for the
    start of a new (kept) table -- the whole dropped table must go."""
    old = (
        "[mcp_servers.pcp]\n"
        'command = "old"\n'
        "matrix = [\n"
        "  [1, 2],\n"
        "]\n\n"
        '[mcp_servers.other]\ncommand = "x"\n'
    )
    out = integ._drop_table(old)
    assert "matrix" not in out and "old" not in out
    assert 'command = "x"' in out


def test_claude_merge_keeps_other_servers():
    existing = json.dumps({"mcpServers": {"other": {"command": "x"}}, "extra": 1})
    out, changed = integ.merge_claude_json(existing, config.claude_mcp_json())
    data = json.loads(out)
    assert changed and data["extra"] == 1 and set(data["mcpServers"]) == {"other", MCP_SERVER_NAME}
    assert integ.merge_claude_json(out, config.claude_mcp_json()) == (out, False)
    with pytest.raises(UsageError):
        integ.merge_claude_json(out, config.claude_mcp_json(pcp="/abs/pcp"))


