"""The Claude Code plugin and the Codex/Claude configs agree with the code (docs/INTEGRATIONS.md).

Every spelling of the ``pcp mcp`` entry is generated by :mod:`pcp.mcp.config`, except
the plugin's static ``.mcp.json``, which is held to the generator here.  The skills and
the AGENTS.md block may only name subcommands, tools and packaged skills that exist, so
a rename breaks a test rather than a lab member's session.
"""

